def smart_search(user_message):
    """Έξυπνο fallback με εκτεταμένη βάση γνώσεων — χωρίς εξωτερικό AI."""
    text = user_message.lower()

    # Έλεγξε FAQ
    for pattern, answer in FAQ:
        if re.search(pattern, text, re.IGNORECASE):
            return "🤖 " + answer

    # Έλεγξε υλικά
    for mat, data in RECYCLING_GUIDE.items():
        if mat in text or mat.replace("ί","ι").replace("ό","ο") in text:
            return (f"♻️ {mat.upper()} → {data['κάδος']}\n"
                    f"• {data['οδηγίες'][0]}\n"
                    f"• {data['οδηγίες'][1]}\n"
                    f"💡 {data['γνωστόν']}")

    # Γενικές ερωτήσεις
    if re.search(r"(πως|πώς|τι|που|πού|ποι)", text):
        return ("🤖 Δεν βρήκα συγκεκριμένη απάντηση, αλλά μπορώ να σε βοηθήσω με:\n"
                "• «πού πετάω [υλικό] στο [περιοχή];» — εύρεση κάδου\n"
                "• «πώς ανακυκλώνω πλαστικό/χαρτί/γυαλί;» — οδηγίες\n"
                "• «δράσεις» — τελευταία νέα ανακύκλωσης\n"
                "• «κουίζ» — παιχνίδι γνώσεων & Πόντοι Bin...go! ")

    return ("🌱 Ρώτα με για ανακύκλωση! Π.χ.:\n"
            "• «πού έχει κάδο γυαλιού στο κέντρο;\"\n"
            "• «πώς ανακυκλώνω αλουμίνιο;\"\n"
            "• «δράσεις» ή «κουίζ»")

