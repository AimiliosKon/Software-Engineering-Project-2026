def handle_material_question(citizen_id, user_input, context):
    """Αναγνωρίζει υλικό και δίνει πλήρη οδηγό."""
    text = user_input.lower()
    
    # Αναγνώριση υλικού
    material_map = {
        "πλαστικό":    r"(πλαστικ|μπουκαλι|pet|hdpe|συσκευασι)",
        "χαρτί":       r"(χαρτι|κουτι|εφημεριδ|περιοδικ|χαρτοκουτ)",
        "γυαλί":       r"(γυαλι|μπουκαλα|βαζο|βάζο|fl.?oz)",
        "αλουμίνιο":   r"(αλουμινι|κουτακι|κουτάκι|αναψυκτ|μπυρ)",
        "μπαταρία":    r"(μπαταρι|battery)",
        "ηλεκτρονικά": r"(ηλεκτρονικ|κινητ|υπολογιστ|τηλεορασ|tablet)",
        "οργανικά":    r"(οργανικ|αποφαγι|φλουδ|λαχανικ|φρουτ)",
        "λάδι":        r"(τηγανελαι|λαδι.*(μαγειρ|τηγαν)|μαγειρικ.?λαδ)",
        "ρούχα":       r"(ρουχ|ρούχ|ενδυσ|παπουτσ)",
    }
    
    found_mat = None
    for mat, pattern in material_map.items():
        if re.search(pattern, text, re.IGNORECASE):
            found_mat = mat
            break
    
    if not found_mat:
        return None  # Δεν βρέθηκε υλικό
    
    guide = RECYCLING_GUIDE[found_mat]
    lines = [f"♻️ {found_mat.upper()} → {guide['κάδος']}\n"]
    lines.append("📋 Οδηγίες:")
    for od in guide["οδηγίες"]:
        lines.append(f"  • {od}")
    lines.append(f"\n💡 Γνωρίζεις ότι: {guide['γνωστόν']}")
    if guide["κωδικοί"]:
        lines.append(f"🔢 Κωδικοί: {', '.join(guide['κωδικοί'])}")
    return "\n".join(lines)

