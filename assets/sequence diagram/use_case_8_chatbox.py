def handle_quiz_answer(citizen_id, answer, context):
    """Διαχειρίζεται απάντηση κουίζ. Επιστρέφει (μήνυμα, quiz_still_active)."""
    phase = context.get("quiz_phase", "easy")
    idx   = context.get("quiz_index", 0)
    qs    = EASY_QUESTIONS if phase == "easy" else HARD_QUESTIONS
    q     = qs[idx]
    correct = answer.strip() in [q["ans"], q["opts"][int(q["ans"])-1].split(")")[1].strip().lower()]

    if correct:
        msg = q["msg"]
        if phase == "easy":
            context["quiz_score_easy"] = context.get("quiz_score_easy", 0) + 1
    else:
        if phase == "easy":
            context["quiz_active"] = False
            return (f"❌ Λάθος! {q['msg']}\n\n🏁 Χρειάζεσαι 4/4 στις εύκολες. Γράψε «κουίζ» για νέα προσπάθεια!", False)
        else:
            _award_points(citizen_id, 100)
            context["quiz_active"] = False
            return (f"❌ Λάθος! {q['msg']}\n\n🏁 Έχασες στο Επίπεδο 2, αλλά κράτησες τους 100 πόντους από το Επίπεδο 1! 👏", False)

    context["quiz_index"] = idx + 1

    # Τέλος εύκολων
    if phase == "easy" and context["quiz_index"] >= len(EASY_QUESTIONS):
        _award_points(citizen_id, 100)
        context["quiz_phase"] = "hard"
        context["quiz_index"] = 0
        nq = HARD_QUESTIONS[0]
        return (
            f"{msg}\n\n"
            "🎉 ΜΠΡΑΒΟ! 4/4 στις εύκολες! +100 Πόντοι πιστώθηκαν!\n"
            "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n"
            "🔴 ΕΠΙΠΕΔΟ 2 — Δύσκολες ερωτήσεις:\n\n"
            f"❓ Δύσκολη 1/5: {nq['q']}\n" + "\n".join(nq["opts"]),
            True
        )

    # Τέλος δύσκολων — ΝΙΚΗ!
    if phase == "hard" and context["quiz_index"] >= len(HARD_QUESTIONS):
        coupon = f"BINGO-{random.randint(10000, 99999)}"
        _award_points(citizen_id, 1200)
        context["quiz_active"] = False
        return (
            f"{msg}\n\n"
            "🥳 ΑΠΙΣΤΕΥΤΟ! ΕΙΣΑΙ MASTER ΑΝΑΚΥΚΛΩΣΗΣ! 🏆\n"
            f"💰 +1200 Πράσινοι Πόντοι πιστώθηκαν!\n"
            f"🎟️ ΚΟΥΠΟΝΙ 3€ → Κωδικός: **{coupon}**\n"
            "Χρησιμοποίησέ το στα καταστήματα-συνεργάτες BinGo!",
            False
        )

    # Επόμενη ερώτηση
    nq        = qs[context["quiz_index"]]
    phase_lbl = "Εύκολη" if phase == "easy" else "Δύσκολη"
    total     = len(EASY_QUESTIONS) if phase == "easy" else len(HARD_QUESTIONS)
    return (
        f"{msg}\n\n"
        f"❓ {phase_lbl} {context['quiz_index']+1}/{total}: {nq['q']}\n" + "\n".join(nq["opts"]),
        True
    )

def _award_points(citizen_id, points):
    if not MYSQL_AVAILABLE: return
    try:
        conn = get_db_connection()
        cur  = conn.cursor()
        cur.execute("UPDATE Citizen SET totalPoints = COALESCE(totalPoints,0) + %s WHERE citizenID=%s",
                    (points, citizen_id))
        conn.commit(); cur.close(); conn.close()
    except Exception: pass

